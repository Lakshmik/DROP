public class StartingStateRealization
{
	private double _forward = Double.NaN;
	private double _forwardVolatility = Double.NaN;

	/**
	 * <i>StartingStateRealization</i> Constructor
	 * 
	 * @param forward Initial Forward
	 * @param forwardVolatility Initial Forward Volatility
	 * 
	 * @throws Exception Thrown if the Inputs are Invalid
	 */

	public StartingStateRealization (
		final double forward,
		final double forwardVolatility)
		throws Exception
	{
		if (!NumberUtil.IsValid (_forward = forward) ||
			!NumberUtil.IsValid (_forwardVolatility = forwardVolatility) || 0. > _forwardVolatility)
		{
			throw new Exception ("StartingStateRealization Constructor => Invalid Inputs");
		}
	}

	/**
	 * Retrieve the Starting Forward
	 * 
	 * @return Starting Forward
	 */

	public double forward()
	{
		return _forward;
	}

	/**
	 * Retrieve the Starting Forward Volatility
	 * 
	 * @return Starting Forward Volatility
	 */

	public double forwardVolatility()
	{
		return _forwardVolatility;
	}
}
