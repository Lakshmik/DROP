public class Himmelblau
	implements R2ToR1
{

	/**
	 * Empty <i>Himmelblau</i> Constructor
	 */

	public Himmelblau()
	{
	}

	/**
	 * Evaluate for the given variate Pair
	 * 
	 * @param x X
	 * @param y Y
	 *  
	 * @return Returns the calculated value
	 * 
	 * @throws Exception Thrown if evaluation cannot be done
	 */

	public double evaluate (
		final double x,
		final double y)
		throws Exception
	{
		if (!NumberUtil.IsValid (x) || !NumberUtil.IsValid (y)) {
			throw new Exception ("Himmelblau::evaluate => Invalid Inputs");
		}

		double f1 = x * x + y - 11.;
		double f2 = x + y * y - 7.;
		return f1 * f1 + f2 * f2;
	}
}
